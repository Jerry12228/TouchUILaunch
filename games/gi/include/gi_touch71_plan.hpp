inline void validate_sites(std::span<const Site> plan) {
    if(plan.empty())throw std::runtime_error("GI: empty patch plan");
    for(size_t i=0;i<plan.size();++i) {
        const auto& site=plan[i];
        if(site.expected.empty()||site.replacement.empty()||site.offset>site.expected.size()||
           site.replacement.size()>site.expected.size()-site.offset||
           uint64_t(site.rva)+site.expected.size()>UINT32_MAX)
            throw std::runtime_error("GI: invalid patch bounds");
        for(size_t j=0;j<i;++j)
            if(uint64_t(site.rva)<uint64_t(plan[j].rva)+plan[j].expected.size()&&
               uint64_t(plan[j].rva)<uint64_t(site.rva)+site.expected.size())
                throw std::runtime_error("GI: overlapping patch sites");
    }
}

// Memory supplies read(rva,size) and write_code(rva,bytes). Validate every site
// before the first write. A mutation failure is fatal: the owner must destroy
// its still-suspended child, never resume a partially initialized process.
template<class Memory>
void apply_plan(Memory& memory,std::span<const Site> plan=sites) {
    validate_sites(plan);
    for(const auto& site:plan) {
        const auto actual=memory.read(site.rva,site.expected.size());
        if(!std::equal(actual.begin(),actual.end(),site.expected.begin(),site.expected.end()))
            throw std::runtime_error(std::string("GI: loaded instruction mismatch at ")+site.name);
    }
    for(const auto& site:plan) {
        memory.write_code(site.rva+site.offset,site.replacement);
        const auto actual=memory.read(site.rva+site.offset,site.replacement.size());
        if(!std::equal(actual.begin(),actual.end(),site.replacement.begin(),site.replacement.end()))
            throw std::runtime_error(std::string("GI: patch verification failed at ")+site.name);
    }
}
